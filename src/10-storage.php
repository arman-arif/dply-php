function ensure_storage(): void
{
    foreach (['', '/keys', '/keys/ssh', '/sessions', '/env-backups', '/home'] as $sub) {
        $d = DPLY_DATA . $sub;
        if (!is_dir($d)) {
            if (!@mkdir($d, 0700, true) && !is_dir($d)) {
                throw new RuntimeException("Cannot create directory $d");
            }
            @chmod($d, 0700);
        }
    }
    $deny = "<IfModule mod_authz_core.c>\n  Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n  Deny from all\n</IfModule>\n";
    if (!is_file(DPLY_DATA . '/.htaccess')) {
        @file_put_contents(DPLY_DATA . '/.htaccess', $deny);
    }
    if (!is_file(DPLY_DATA . '/index.html')) {
        @file_put_contents(DPLY_DATA . '/index.html', '');
    }
    if (!is_file(DPLY_DIR . '/.htaccess')) {
        @file_put_contents(DPLY_DIR . '/.htaccess', "# Generated by DPLY: only index.php is reachable.\n"
            . "Options -Indexes\nDirectoryIndex index.php\n"
            . "<FilesMatch \"^(?!index\\.php$).+\">\n$deny</FilesMatch>\n"
            . "<IfModule mod_rewrite.c>\n  RewriteEngine On\n"
            . "  RewriteRule .* - [E=HTTP_AUTHORIZATION:%{HTTP:Authorization}]\n</IfModule>\n");
    }
}

function db(): PDO
{
    static $pdo = null;
    if ($pdo) {
        return $pdo;
    }
    $new = !is_file(DPLY_DB);
    $pdo = new PDO('sqlite:' . DPLY_DB, null, null, [
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
    if ($new) {
        @chmod(DPLY_DB, 0600);
    }
    $pdo->exec('PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON; PRAGMA busy_timeout=5000;');
    $pdo->exec(<<<SQL
        CREATE TABLE IF NOT EXISTS settings (k TEXT PRIMARY KEY, v TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT NOT NULL UNIQUE COLLATE NOCASE,
            password_hash TEXT NOT NULL,
            perms TEXT NOT NULL DEFAULT '',
            active INTEGER NOT NULL DEFAULT 1,
            totp_secret TEXT,
            totp_last INTEGER NOT NULL DEFAULT 0,
            failed_count INTEGER NOT NULL DEFAULT 0,
            locked_until INTEGER NOT NULL DEFAULT 0,
            session_version INTEGER NOT NULL DEFAULT 1,
            created_at INTEGER NOT NULL,
            last_login_at INTEGER,
            last_login_ip TEXT
        );
        CREATE TABLE IF NOT EXISTS attempts (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            ip TEXT NOT NULL, username TEXT, kind TEXT NOT NULL, created_at INTEGER NOT NULL
        );
        CREATE INDEX IF NOT EXISTS attempts_ip ON attempts (ip, created_at);
        CREATE TABLE IF NOT EXISTS blocks (
            ip TEXT PRIMARY KEY, until INTEGER NOT NULL, strikes INTEGER NOT NULL DEFAULT 1,
            reason TEXT, created_at INTEGER NOT NULL
        );
        CREATE TABLE IF NOT EXISTS deployments (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            actor TEXT NOT NULL, kind TEXT NOT NULL, branch TEXT, status TEXT NOT NULL,
            commit_before TEXT, commit_after TEXT, steps TEXT, log TEXT,
            started_at INTEGER NOT NULL, finished_at INTEGER
        );
        CREATE TABLE IF NOT EXISTS audit (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            actor TEXT, ip TEXT, action TEXT NOT NULL, detail TEXT, created_at INTEGER NOT NULL
        );
        CREATE INDEX IF NOT EXISTS audit_time ON audit (created_at);
        SQL);
    db_migrate($pdo);
    return $pdo;
}

