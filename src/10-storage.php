function settings_all(): array
{
    static $cache = null;
    if ($cache === null || isset($GLOBALS['__dply_settings_dirty'])) {
        unset($GLOBALS['__dply_settings_dirty']);
        $cache = setting_defaults();
        foreach (db()->query('SELECT k, v FROM settings') as $r) {
            $cache[$r['k']] = $r['v'];
        }
    }
    return $cache;
}

/** Global setting, or — for keys in DPLY_PROJECT_KEYS — the current project's value. */
function setting(string $k): string
{
    if (is_project_key($k)) {
        $p = current_project();
        return $p ? project_setting($p['id'], $k) : (string) (setting_defaults()[$k] ?? '');
    }
    return (string) (settings_all()[$k] ?? '');
}

function set_setting(string $k, string $v): void
{
    if (is_project_key($k)) {
        $p = current_project();
        if (!$p) {
            throw new RuntimeException("No current project to store '$k' in.");
        }
        set_project_setting($p['id'], $k, $v);
        return;
    }
    db()->prepare('INSERT INTO settings (k, v) VALUES (?, ?) ON CONFLICT(k) DO UPDATE SET v = excluded.v')->execute([$k, $v]);
    $GLOBALS['__dply_settings_dirty'] = true;
}

function secret_key(): string
{
    $f = DPLY_DATA . '/keys/secret.key';
    if (!is_file($f)) {
        file_put_contents($f, random_bytes(32), LOCK_EX);
        @chmod($f, 0600);
    }
    $k = (string) file_get_contents($f);
    if (strlen($k) !== 32) {
        throw new RuntimeException('Corrupt secret key file.');
    }
    return $k;
}

function enc(string $plain): string
{
    if ($plain === '') {
        return '';
    }
    $k = secret_key();
    if (function_exists('sodium_crypto_secretbox')) {
        $n = random_bytes(SODIUM_CRYPTO_SECRETBOX_NONCEBYTES);
        return 's1:' . base64_encode($n . sodium_crypto_secretbox($plain, $n, $k));
    }
    $iv = random_bytes(12);
    $tag = '';
    $c = openssl_encrypt($plain, 'aes-256-gcm', $k, OPENSSL_RAW_DATA, $iv, $tag);
    return 'o1:' . base64_encode($iv . $tag . $c);
}

function dec(string $v): string
{
    if ($v === '') {
        return '';
    }
    $raw = base64_decode(substr($v, 3), true);
    if ($raw === false) {
        return '';
    }
    $k = secret_key();
    if (str_starts_with($v, 's1:') && function_exists('sodium_crypto_secretbox_open')) {
        $p = sodium_crypto_secretbox_open(substr($raw, 24), substr($raw, 0, 24), $k);
        return $p === false ? '' : $p;
    }
    if (str_starts_with($v, 'o1:')) {
        $p = openssl_decrypt(substr($raw, 28), 'aes-256-gcm', $k, OPENSSL_RAW_DATA, substr($raw, 0, 12), substr($raw, 12, 16));
        return $p === false ? '' : $p;
    }
    return '';
}

function hash_pw(string $pw): string
{
    return password_hash($pw, defined('PASSWORD_ARGON2ID') ? PASSWORD_ARGON2ID : PASSWORD_BCRYPT);
}

function pw_policy(string $pw, string $username = ''): ?string
{
    if (strlen($pw) < 12) {
        return 'Password must be at least 12 characters.';
    }
    if (strlen($pw) > 1024) {
        return 'Password is too long.';
    }
    if ($username !== '' && strcasecmp($pw, $username) === 0) {
        return 'Password must not equal the username.';
    }
    return null;
}

function setup_done(): bool
{
    if (setting('http_user') === '' || setting('http_pass_hash') === '') {
        return false;
    }
    return (int) db()->query("SELECT COUNT(*) FROM users WHERE active = 1 AND (',' || perms || ',') LIKE '%,admin,%'")->fetchColumn() > 0;
}

function audit(string $action, string $detail = '', ?string $actor = null, ?string $ip = null): void
{
    if ($actor === null) {
        $u = PHP_SAPI === 'cli' ? null : current_user();
        $actor = $u['username'] ?? (PHP_SAPI === 'cli' ? 'cli' : '-');
    }
    db()->prepare('INSERT INTO audit (actor, ip, action, detail, created_at, project_id) VALUES (?, ?, ?, ?, ?, ?)')
        ->execute([$actor, $ip ?? (PHP_SAPI === 'cli' ? 'cli' : client_ip()), $action, substr($detail, 0, 2000), time(), audit_project_id($action)]);
}

/** Only actions that act on a project are tagged with it; global ones (users, security, auth) are not. */
function audit_project_id(string $action): ?int
{
    return preg_match('/^(deploy|artisan|terminal|env|settings|project)\.|^keys\.activate$/', $action) ? resolved_project_id() : null;
}
